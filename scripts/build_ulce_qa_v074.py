def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    output = copy.deepcopy(data)
    by_id = {item["id"]: item for item in output["qas"]}

    missing = sorted(set(EXPANSIONS) - set(by_id))
    if missing:
        raise ValueError(f"Expansion IDs not found: {missing}")

    starter_ids = {item["id"] for item in output["qas"] if item.get("starter")}
    if starter_ids != set(EXPANSIONS):
        raise ValueError(
            "Every starter question must receive a full explanation: "
            f"missing={sorted(starter_ids - set(EXPANSIONS))}, "
            f"extra={sorted(set(EXPANSIONS) - starter_ids)}"
        )

    for item_id, addition in EXPANSIONS.items():
        item = by_id[item_id]
        original = item["answer"].strip()
        item["answer"] = f"{original}\n\n{addition['explanation']}"
        item["example"] = addition["example"]
        item["misunderstanding"] = addition["misunderstanding"]
        item["explanationDepth"] = "detailed"

    output["version"] = VERSION
    output["summary"]["expandedQaCount"] = len(EXPANSIONS)
    output["qaWorkflow"]["version"] = VERSION
    output["qaWorkflow"]["explanationStandard"] = (
        "主要Q&Aは、短い結論の後に背景・仕組み・具体例・よくある誤解・実務手順・完了条件を示す。"
    )

    OUTPUT.write_text(
        json.dumps(output, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )

    lengths = [len(by_id[item_id]["answer"]) for item_id in EXPANSIONS]
    print(
        json.dumps(
            {
                "version": VERSION,
                "qaCount": len(output["qas"]),
                "expanded": len(EXPANSIONS),
                "answerCharsMin": min(lengths),
                "answerCharsMax": max(lengths),
                "result": "PASS",
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
