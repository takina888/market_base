def workflow_fields(
    *,
    stage: str,
    priority: int,
    audience: list[str],
    why: str,
    action_label: str,
    action_items: list[str],
    plain_terms: list[str] | None = None,
    template: str | None = None,
    completion: str | None = None,
    caution: str | None = FACT_CAUTION,
) -> dict:
    fields = {
        "stage": stage,
        "starter": True,
        "featured": priority <= len(FEATURED_IDS),
        "priority": priority,
        "audience": audience,
        "why": why,
        "actionLabel": action_label,
        "actionItems": action_items,
        "plainTerms": plain_terms or [],
    }
    if template:
        fields["template"] = template
    if completion:
        fields["completion"] = completion
    if caution:
        fields["caution"] = caution
    return fields


def starter(
    *,
    question: str,
    short_answer: str,
    answer: str,
    stage: str,
    audience: list[str],
    why: str,
    action_label: str,
    action_items: list[str],
    plain_terms: list[str] | None = None,
    template: str | None = None,
    completion: str | None = None,
    caution: str | None = FACT_CAUTION,
) -> dict:
    return {
        "question": question,
        "shortAnswer": short_answer,
        "answer": answer,
        # The old one-line action was often a slogan or unexplained internal
        # term.  Starter cards use actionLabel/actionItems instead.
        "action": "",
        **workflow_fields(
            stage=stage,
            priority=0,  # Assigned from STARTER_IDS after all records are merged.
            audience=audience,
            why=why,
            action_label=action_label,
            action_items=action_items,
            plain_terms=plain_terms,
            template=template,
            completion=completion,
            caution=caution,
        ),
    }


