def prepare_legacy_question(question: dict, index: int) -> dict:
    item = copy.deepcopy(question)
    stage = CATEGORY_STAGE.get(item.get("category"), "judge")
    item.update(
        {
            "stage": stage,
            "starter": False,
            "featured": False,
            "priority": 1000 + index,
            "audience": copy.deepcopy(CATEGORY_AUDIENCE.get(item.get("category"), ["実務担当"])),
            "why": GENERIC_WHY[stage],
            "actionLabel": "確認すること",
            "actionItems": [item["action"]] if item.get("action") else [],
            "plainTerms": [],
        }
    )
    return item


def apply_starter_rewrite(item: dict, rewrite: dict, priority: int) -> dict:
    merged = copy.deepcopy(item)
    merged.update(copy.deepcopy(rewrite))
    merged["priority"] = priority
    merged["starter"] = True
    merged["featured"] = priority <= len(FEATURED_IDS)
    merged["action"] = " ".join(merged["actionItems"])
    return merged


def validate(data: dict, original_ids: set[str]) -> None:
    questions = data["qas"]
    ids = [question["id"] for question in questions]
    assert len(ids) == 303, f"expected 303 Q&As, got {len(ids)}"
    assert len(set(ids)) == len(ids), "duplicate Q&A IDs"
    assert original_ids <= set(ids), "one or more v072 Q&As were lost"
    assert set(NEW_QUESTIONS) <= set(ids), "new v073 Q&As are missing"
    assert ids[: len(FEATURED_IDS)] == FEATURED_IDS, "featured Q&A order changed"
    assert data["version"] == VERSION
    assert data["summary"]["qaCount"] == len(questions)
    assert data["summary"]["starterQaCount"] == len(STARTER_IDS) == 38
    assert data["summary"]["featuredQaCount"] == len(FEATURED_IDS) == 8

    required = {
        "stage",
        "starter",
        "featured",
        "priority",
        "audience",
        "why",
        "actionLabel",
        "actionItems",
        "plainTerms",
    }
    for question in questions:
        missing = required - set(question)
        assert not missing, f"{question['id']} missing {sorted(missing)}"
        assert question["stage"] in ALLOWED_STAGES, f"invalid stage: {question['id']}"
        assert isinstance(question["starter"], bool)
        assert isinstance(question["featured"], bool)
        assert isinstance(question["priority"], int)
        assert isinstance(question["audience"], list) and question["audience"]
        assert isinstance(question["why"], str) and question["why"].strip()
        assert isinstance(question["actionLabel"], str)
        assert isinstance(question["actionItems"], list)
        assert isinstance(question["plainTerms"], list)

    starters = [question for question in questions if question["starter"]]
    featured = [question for question in questions if question["featured"]]
    assert len(starters) == 38
    assert [question["id"] for question in featured] == FEATURED_IDS
    assert [question["priority"] for question in starters] == list(range(1, 39))
    for question in starters:
        assert len(question["actionItems"]) >= 3, f"starter lacks concrete actions: {question['id']}"
        assert question.get("completion"), f"starter lacks completion condition: {question['id']}"
        assert question.get("caution"), f"starter lacks caution: {question['id']}"


def main() -> None:
    source_data = json.loads(SOURCE.read_text(encoding="utf-8"))
    source_questions = source_data.get("qas", [])
    assert len(source_questions) == 300, "v072 canonical Q&A count changed"
    original_ids = {question["id"] for question in source_questions}
    assert len(original_ids) == 300, "v072 contains duplicate Q&A IDs"
    assert not (set(NEW_QUESTIONS) & original_ids), "new Q&A ID already exists in v072"

    prepared = {
        question["id"]: prepare_legacy_question(question, index)
        for index, question in enumerate(source_questions, start=1)
    }

    for question_id, base in NEW_QUESTIONS.items():
        prepared[question_id] = prepare_legacy_question(base, 300 + len(prepared))

    for priority, question_id in enumerate(STARTER_IDS, start=1):
        if question_id in REWRITES:
            rewrite = REWRITES[question_id]
        elif question_id == "QA-FLD-013":
            rewrite = NEW_QUESTIONS[question_id]
        else:
            raise AssertionError(f"starter rewrite missing: {question_id}")
        prepared[question_id] = apply_starter_rewrite(prepared[question_id], rewrite, priority)

    # Featured questions first, then the remainder of the workflow starters, then
    # every retained detail question in its original v072 order.
    ordered_ids = STARTER_IDS + [
        question["id"] for question in source_questions if question["id"] not in STARTER_IDS
    ]
    ordered_ids += [question_id for question_id in NEW_QUESTIONS if question_id not in STARTER_IDS]

    result = copy.deepcopy(source_data)
    result["version"] = VERSION
    result["summary"]["qaCount"] = len(ordered_ids)
    result["summary"]["starterQaCount"] = len(STARTER_IDS)
    result["summary"]["featuredQaCount"] = len(FEATURED_IDS)
    result["qaWorkflow"] = {
        "version": VERSION,
        "principle": "初心者から出荷・据付まで、読者の仕事の順で主要Q&Aを表示する。制度内容は案件ごとに一次資料で要確認。",
        "stages": [
            {"id": stage, "label": STAGE_LABELS[stage], "order": index}
            for index, stage in enumerate(ALLOWED_STAGES, start=1)
        ],
        "featuredIds": FEATURED_IDS,
        "starterIds": STARTER_IDS,
        "detailCount": len(ordered_ids) - len(STARTER_IDS),
    }
    result["qas"] = [prepared[question_id] for question_id in ordered_ids]

    validate(result, original_ids)
    OUTPUT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(
        json.dumps(
            {
                "status": "ok",
                "version": result["version"],
                "qaCount": result["summary"]["qaCount"],
                "retainedV072": len(original_ids),
                "added": len(NEW_QUESTIONS),
                "starter": result["summary"]["starterQaCount"],
                "featured": result["summary"]["featuredQaCount"],
                "output": str(OUTPUT),
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
